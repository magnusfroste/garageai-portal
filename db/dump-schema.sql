-- Reads the portal's live schema as DDL, one row per object: (s = section, k = name, ddl).
-- Read-only (SELECT only). Run it where you can reach the database (Lovable's query tool,
-- psql), save the result as JSON {"rows": [...]} and build the file with:
--   python3 db/build_schema.py result.json db/schema.sql
-- Sections: 10 types, 20 sequences, 30 tables, 40 keys/unique/check, 50 foreign keys,
-- 60 indexes, 70 functions, 80 triggers, 90 RLS, 100 policies, 120 buckets, 130 cron.
-- Supabase's own storage triggers are left out; Bearer tokens in cron commands are redacted.
with
enums as (
 select 10 s, t.typname::text k, format('CREATE TYPE public.%I AS ENUM (%s);', t.typname,
   (select string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder) from pg_enum e where e.enumtypid=t.oid)) ddl
 from pg_type t join pg_namespace n on n.oid=t.typnamespace where n.nspname='public' and t.typtype='e'),
seqs as (
 select 20 s, c.relname::text k, format('CREATE SEQUENCE IF NOT EXISTS public.%I;', c.relname) ddl
 from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname='public' and c.relkind='S'
   and not exists (select 1 from pg_depend d where d.objid=c.oid and d.deptype='i')),
tabs as (
 select 30 s, c.relname::text k, format(E'CREATE TABLE public.%I (\n%s\n);', c.relname,
   (select string_agg(format('  %I %s%s%s%s', a.attname, format_type(a.atttypid,a.atttypmod),
      case when a.attidentity='a' then ' GENERATED ALWAYS AS IDENTITY' when a.attidentity='d' then ' GENERATED BY DEFAULT AS IDENTITY' else '' end,
      case when a.attgenerated='s' then ' GENERATED ALWAYS AS ('||pg_get_expr(ad.adbin,ad.adrelid)||') STORED'
           when ad.adbin is not null then ' DEFAULT '||pg_get_expr(ad.adbin,ad.adrelid) else '' end,
      case when a.attnotnull then ' NOT NULL' else '' end), E',\n' order by a.attnum)
    from pg_attribute a left join pg_attrdef ad on ad.adrelid=a.attrelid and ad.adnum=a.attnum
    where a.attrelid=c.oid and a.attnum>0 and not a.attisdropped)) ddl
 from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname='public' and c.relkind in ('r','p')),
cons as (
 select case when co.contype='f' then 50 else 40 end s, cl.relname||'.'||co.conname k,
   format('ALTER TABLE ONLY public.%I ADD CONSTRAINT %I %s;', cl.relname, co.conname, pg_get_constraintdef(co.oid)) ddl
 from pg_constraint co join pg_class cl on cl.oid=co.conrelid join pg_namespace n on n.oid=cl.relnamespace
 where n.nspname='public' and co.contype in ('p','u','c','f','x')),
idx as (
 select 60 s, i.indexname::text k, i.indexdef||';' ddl from pg_indexes i
 where i.schemaname='public' and not exists (select 1 from pg_constraint co where co.conname=i.indexname and co.connamespace='public'::regnamespace)),
funcs as (
 select 70 s, p.proname||'('||pg_get_function_identity_arguments(p.oid)||')' k, pg_get_functiondef(p.oid)||';' ddl
 from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and p.prokind in ('f','p')),
trg as (
 select 80 s, n.nspname||'.'||c.relname||'.'||tg.tgname k, pg_get_triggerdef(tg.oid)||';' ddl
 from pg_trigger tg join pg_class c on c.oid=tg.tgrelid join pg_namespace n on n.oid=c.relnamespace
 where not tg.tgisinternal and n.nspname in ('public','auth')),
rls as (
 select 90 s, c.relname::text k, format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY;', c.relname) ddl
 from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname='public' and c.relkind='r' and c.relrowsecurity),
pol as (
 select 100 s, schemaname||'.'||tablename||'.'||policyname k,
   format('CREATE POLICY %I ON %I.%I AS %s FOR %s TO %s%s%s;', policyname, schemaname, tablename, permissive, cmd,
     array_to_string(roles, ', '), coalesce(E'\n  USING ('||qual||')',''), coalesce(E'\n  WITH CHECK ('||with_check||')','')) ddl
 from pg_policies where schemaname in ('public','storage')),
pub as (
 select 110 s, pubname||'.'||tablename k, format('ALTER PUBLICATION %I ADD TABLE %I.%I;', pubname, schemaname, tablename) ddl
 from pg_publication_tables where schemaname='public'),
bkt as (
 select 120 s, id::text k, format('INSERT INTO storage.buckets (id, name, public) VALUES (%L, %L, %s);', id, name, case when public then 'true' else 'false' end) ddl from storage.buckets),
crn as (
 select 130 s, jobname::text k, format('SELECT cron.schedule(%L, %L, %L);', jobname, schedule,
   regexp_replace(command, 'Bearer [A-Za-z0-9._-]+', 'Bearer <REDACTED>', 'g')) ddl from cron.job)
select s, k, ddl from (
 select * from enums union all select * from seqs union all select * from tabs union all select * from cons union all
 select * from idx union all select * from funcs union all select * from trg union all select * from rls union all
 select * from pol union all select * from pub union all select * from bkt union all select * from crn) x
order by s, k;
